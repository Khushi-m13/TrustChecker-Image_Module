def assess_image_risk(analysis, language="English"):

    translations = MESSAGES.get(
        language, MESSAGES["English"]
    )

    ai_assessment = analysis.get(
        "assessment", "inconclusive"
    )

    scam_assessment = analysis.get(
        "scam_assessment", "insufficient_information"
    )

    ai_title, ai_description = translations["ai"].get(
        ai_assessment,
        translations["ai"]["inconclusive"]
    )

    scam_title, scam_description = translations["scam"].get(
        scam_assessment,
        translations["scam"]["insufficient_information"]
    )

    if scam_assessment in {
        "likely_scam",
        "suspicious_needs_verification"
    }:
        recommendation = translations["recommendations"]["caution"]

    elif scam_assessment == "no_obvious_scam_indicators":
        recommendation = translations["recommendations"]["safe"]

    else:
        recommendation = translations["recommendations"]["review"]

    return {
        # Image origin assessment
        "ai_title": ai_title,
        "ai_description": ai_description,

        # Scam assessment
        "scam_title": scam_title,
        "scam_description": scam_description,

        # Safety recommendation
        "safety_recommendation": recommendation,

        # Backward compatibility with the previous app
        "review_priority": ai_title,
        "description": ai_description
    }
